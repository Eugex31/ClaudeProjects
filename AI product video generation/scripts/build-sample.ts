import { mkdirSync, writeFileSync } from "node:fs";
import { GLTFExporter } from "three/examples/jsm/exporters/GLTFExporter.js";
import { buildBookshelf } from "../lib/sample/bookshelf";
import { SAMPLE_MANUAL, SAMPLE_PROJECT_NAME, SAMPLE_STEPS } from "../lib/sample/storyboard";
import { extractManifest } from "../lib/three/manifest";

// GLTFExporter uses FileReader to turn Blobs into ArrayBuffers; Node has Blob but no FileReader.
class NodeFileReader {
  result: ArrayBuffer | string | null = null;
  onloadend: (() => void) | null = null;
  readAsArrayBuffer(blob: Blob) { blob.arrayBuffer().then((b) => { this.result = b; this.onloadend?.(); }); }
  readAsDataURL(blob: Blob) {
    blob.arrayBuffer().then((b) => {
      this.result = `data:${blob.type || "application/octet-stream"};base64,${Buffer.from(b).toString("base64")}`;
      this.onloadend?.();
    });
  }
}
(globalThis as any).FileReader ??= NodeFileReader;

// Content is embedded in dollar-quoted SQL literals; fail loudly if it could terminate one.
function assertSafe(label: string, text: string) {
  for (const tag of ["$json$", "$manual$", "$name$"]) {
    if (text.includes(tag)) throw new Error(`${label} contains ${tag}, which would break the generated SQL`);
  }
}

async function main() {
  const shelf = buildBookshelf();
  const parts = extractManifest(shelf);
  const glb = (await new GLTFExporter().parseAsync(shelf, { binary: true })) as ArrayBuffer;

  const partsJson = JSON.stringify(parts);
  const stepsJson = JSON.stringify(SAMPLE_STEPS);
  assertSafe("project name", SAMPLE_PROJECT_NAME);
  assertSafe("manual", SAMPLE_MANUAL);
  assertSafe("parts json", partsJson);
  assertSafe("steps json", stepsJson);

  mkdirSync("public/sample", { recursive: true });
  writeFileSync("public/sample/bookshelf.glb", Buffer.from(glb));
  writeFileSync("public/sample/bookshelf-manual.txt", SAMPLE_MANUAL);

  const json = (s: string) => `$json$${s}$json$::jsonb`;
  const sql = `-- Generated by \`npm run build:sample\`. Do not edit by hand.
insert into public.sample_templates (id, project_name, manual_text, parts, steps, model_path)
values ('bookshelf', $name$${SAMPLE_PROJECT_NAME}$name$, $manual$${SAMPLE_MANUAL}$manual$, ${json(partsJson)}, ${json(stepsJson)}, 'bookshelf.glb')
on conflict (id) do update set project_name = excluded.project_name, manual_text = excluded.manual_text,
  parts = excluded.parts, steps = excluded.steps, model_path = excluded.model_path;
`;
  writeFileSync("supabase/migrations/0004_sample_template.sql", sql);
  console.log(`Wrote bookshelf.glb (${glb.byteLength} bytes, ${parts.length} parts) and 0004_sample_template.sql`);
}

main().catch((e) => { console.error(e); process.exit(1); });
